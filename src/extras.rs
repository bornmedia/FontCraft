//! Extra tools: CSS export, printable specimens and collection export.


use crate::library::FaceMeta;

use std::path::{Path, PathBuf};

fn file_url(p: &Path) -> String {
    let s = p.to_string_lossy().replace('\\', "/");
    let s = s.replace(' ', "%20").replace('#', "%23");
    if s.starts_with('/') {
        format!("file://{s}")
    } else {
        format!("file:///{s}")
    }
}

fn css_format(p: &Path) -> &'static str {
    match p.extension().map(|e| e.to_string_lossy().to_ascii_lowercase()).as_deref() {
        Some("otf") | Some("otc") => "opentype",
        Some("ttc") => "collection",
        _ => "truetype",
    }
}

/// `@font-face` rules for the given faces. `local_urls` points at the files on this
/// computer; otherwise just the file names are used (for copying next to the CSS).
pub fn css_for(faces: &[&FaceMeta], local_urls: bool) -> String {
    let mut out = String::from("/* Generated by FontCraft */\n");
    for f in faces {
        let url = if local_urls {
            file_url(&f.path)
        } else {
            f.path.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default()
        };
        let weight = if f.axes.iter().any(|a| a.tag == "wght") {
            let a = f.axes.iter().find(|a| a.tag == "wght").unwrap();
            format!("{:.0} {:.0}", a.min, a.max)
        } else {
            f.weight.to_string()
        };
        out.push_str(&format!(
            "@font-face {{\n  font-family: \"{}\";\n  src: local(\"{}\"), url(\"{}\") format(\"{}\");\n  font-weight: {};\n  font-style: {};\n  font-display: swap;\n}}\n\n",
            f.family,
            if f.postscript.is_empty() { &f.full_name } else { &f.postscript },
            url,
            css_format(&f.path),
            weight,
            if f.italic { "italic" } else { "normal" }
        ));
    }
    out
}

fn esc(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
}

/// Writes a printable specimen page and returns its path.
pub fn write_specimen(title: &str, families: &[(String, Vec<&FaceMeta>)], sample: &str) -> std::io::Result<PathBuf> {
    let dir = crate::config::data_dir().join("specimens");
    std::fs::create_dir_all(&dir)?;
    let safe: String = title.chars().map(|c| if c.is_alphanumeric() { c } else { '_' }).collect();
    let path = dir.join(format!("{safe}.html"));
    let mut css = String::new();
    let mut body = String::new();
    let mut n = 0;
    for (fam, faces) in families {
        body.push_str(&format!("<section><h2>{}</h2>", esc(fam)));
        for f in faces {
            n += 1;
            css.push_str(&format!(
                "@font-face{{font-family:\"fc{n}\";src:url(\"{}\");}}\n",
                file_url(&f.path)
            ));
            body.push_str(&format!(
                "<div class=s><div class=l>{}</div><div style=\"font-family:fc{n};font-size:32px\">{}</div><div style=\"font-family:fc{n};font-size:14px\">ABCDEFGHIJKLMNOPQRSTUVWXYZ abcdefghijklmnopqrstuvwxyz 0123456789</div></div>",
                esc(&f.style),
                esc(sample)
            ));
        }
        body.push_str("</section>");
    }
    let html = format!(
        "<!doctype html><html><head><meta charset=utf-8><title>{t} – FontCraft specimen</title><style>{css}\
body{{font-family:system-ui,sans-serif;margin:40px;color:#111}}h1{{font-size:28px}}h2{{font-size:16px;border-bottom:1px solid #ddd;padding-bottom:6px;margin-top:32px}}\
.s{{margin:14px 0;break-inside:avoid}}.l{{font-size:11px;color:#888;text-transform:uppercase;letter-spacing:.05em}}\
@media print{{button{{display:none}}}}</style></head><body><button onclick=\"print()\">Print</button><h1>{t}</h1>{body}</body></html>",
        t = esc(title)
    );
    std::fs::write(&path, html)?;
    Ok(path)
}

pub fn open_file(p: &Path) {
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        let _ = std::process::Command::new("cmd").args(["/C", "start", ""]).arg(p).creation_flags(0x0800_0000).spawn();
    }
    #[cfg(target_os = "macos")]
    {
        let _ = std::process::Command::new("open").arg(p).spawn();
    }
    #[cfg(all(unix, not(target_os = "macos")))]
    {
        let _ = std::process::Command::new("xdg-open").arg(p).spawn();
    }
}

/// Copy font files into a folder. Returns how many were copied.
pub fn copy_files(files: &[PathBuf], dest: &Path) -> usize {
    let _ = std::fs::create_dir_all(dest);
    let mut n = 0;
    for f in files {
        if let Some(name) = f.file_name() {
            let target = dest.join(name);
            if target.exists() {
                continue;
            }
            if std::fs::copy(f, &target).is_ok() {
                n += 1;
            }
        }
    }
    n
}
